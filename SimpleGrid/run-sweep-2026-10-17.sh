#!/bin/bash
# run-sweep-2026-10-17.sh -- the 8x8-10x10 knowledge-compilation sweep with the
# fixed d4 (d4v2 c11210d), then the recognition (marginal inference) suite on
# 7x7-10x10.  Every run is limited to 20 minutes of awake time.
#
# Run it detached and kept awake, from SimpleGrid/:
#   nohup caffeinate -i bash run-sweep-2026-10-17.sh > LOG 2>&1 &
# Every stage appends one JSON record per run the moment it ends, and the
# compile and recognition stages skip runs already recorded, so after an
# interruption the script can simply be started again (--skip-compile skips
# stage 1 altogether).
#
# Stages:
#   1. compile-d4.py: 8x8, 9x9, 10x10, one at a time (two SBCL imports at once
#      swap on this 16 GB machine); larger grids are skipped if none of a size
#      compiles in time.
#   2. goals/ and evidence/ for 8x8-10x10, by make-instances.sh in a scratch
#      copy (its ppgen step rewrites the problem files); the regenerated
#      problems must be byte-identical to the committed ones.
#   3. query-evidence.py: a two-observation query on each new circuit.
#   4. run-recognize.py: max-term, sharpsat-td and mc-sat on every pinned
#      evidence file of 7x7, then 8x8, 9x9, 10x10 (8 runs at once).
set -uo pipefail
cd "$(dirname "$0")" || exit 2
export FIFO_LISP=/Users/kautz/Programming/FiFO/lisp
LIMIT=1200
stamp() { echo "=== $(date '+%Y-%m-%d %H:%M:%S') $*"; }

if [ "${1:-}" != "--skip-compile" ]; then
  stamp "stage 1: compile 8x8-10x10"
  # Problems already compiled with this FiFO and this d4 are skipped (records of
  # the buggy d4 do not count).  One attempt each: the fixed d4 no longer fails
  # at random, and a failure to import a circuit (SBCL's heap) is deterministic.
  python3 compile-d4.py --sizes 8x8,9x9,10x10 --jobs 1 --limit "$LIMIT" --attempts 1 \
          --sbcl-heap-mb 12288 --node-limit 50000000 || stamp "compile-d4.py exited $?"
fi

stamp "stage 2: goals and evidence for 8x8-10x10"
# size  goals  mindist  max observations (N-1, as for 3x3-7x7)
# (9x9 and 10x10 had their goals and mindist swapped here when the sweep ran on
# 2026-10-17; their evidence was regenerated by hand with these values)
for spec in "8 7 9 7" "9 8 10 8" "10 9 11 9"; do
  set -- $spec
  n=$1
  if ls evidence/grid${n}x${n}-*-obs1.txt >/dev/null 2>&1; then
    stamp "  ${n}x${n}: evidence exists, skipped"
    continue
  fi
  gen="$(mktemp -d /tmp/sg-gen.XXXXXX)"
  cp make-instances.sh "$gen/"
  if ! bash "$gen/make-instances.sh" "$@"; then
    stamp "  ${n}x${n}: make-instances.sh failed; no evidence for this size"
    continue
  fi
  same=1
  for s in 1 2 3 4; do
    cmp -s "$gen/grid${n}x${n}-$s.pddl" "grid${n}x${n}-$s.pddl" || same=0
  done
  if [ "$same" -ne 1 ]; then
    stamp "  ${n}x${n}: regenerated problems differ from the committed ones; evidence NOT copied ($gen)"
    continue
  fi
  cp -n "$gen"/goals/* goals/
  cp -n "$gen"/evidence/* evidence/
  rm -rf "$gen"
  stamp "  ${n}x${n}: goals and evidence copied"
done

stamp "stage 3: two-observation queries on the new circuits"
python3 query-evidence.py --max-size 10 grid8x8-1 grid8x8-2 grid8x8-3 grid8x8-4 \
        grid9x9-1 grid9x9-2 grid9x9-3 grid9x9-4 \
        grid10x10-1 grid10x10-2 grid10x10-3 grid10x10-4 || stamp "query-evidence.py exited $?"

stamp "stage 4: recognition suite, 7x7-10x10"
for size in 7x7 8x8 9x9 10x10; do
  stamp "  $size"
  python3 run-recognize.py --methods max-term,sharpsat-td,mc-sat --limit "$LIMIT" \
          --jobs 8 --match "^evidence/grid${size}-" --work /tmp/sg-rec \
          || stamp "run-recognize.py exited $? on $size"
done
stamp "done"
