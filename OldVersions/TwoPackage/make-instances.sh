#!/bin/bash
# make-instances.sh N [SEEDS...]
#
# Generate TwoPackage problems gridNxN-K.pddl -- an N x N grid, no airports, one
# truck and two packages placed at random, two possible destinations per package
# (never a package's own start; the two packages may share one), and the goal
# that AT LEAST ONE package reaches one of its destinations (ppgen --require
# some).  The recognition hypotheses are the goal's four literals
# (at pkgI place).  For each problem and each goal literal:
#   goals/<problem>-<pkg>-<place>.pddl     the problem narrowed to that literal
#   goals/<problem>-<pkg>-<place>.answer   a shortest plan for it (planner.sh)
#   goals/<problem>-<pkg>-<place>-clean.answer  the same plan without any load
#                                          or unload of the other package
#   evidence/<problem>-<pkg>-<place>-obsK.txt  the plan's first K actions (drive,
#                                             load or unload), pinned to slices
#   evidence/<problem>-<pkg>-<place>-ordK.txt  the same actions as an ordering only
# for K = 1 .. min(N-2, number of actions in the plan).  Seeds default to
# 1 2 3 4.  Run from TwoPackage/ (or anywhere: it cds to its own directory).
set -euo pipefail
N="$1"; shift
SEEDS=("$@"); [[ ${#SEEDS[@]} -gt 0 ]] || SEEDS=(1 2 3 4)
cd "$(dirname "$0")"
mkdir -p goals evidence
MAXOBS=$((N - 2))

# The single-goal variant: the goal narrowed to one literal, the problem
# renamed, and the ppgen settings block dropped (it would not regenerate this
# file) in favour of a line saying where it came from.
single_goal() {   # single_goal <problem.pddl> <pkg> <place>
  awk -v src="$1" -v pkg="$2" -v dest="$3" '
    NR == 1 { print $0 "-" pkg "-" dest
              print ";; Single-goal variant of " src ": the goal is (at " pkg " " dest ") only."
              next }
    /^;; Generated by ppgen.sh/ { skip = 1; next }
    skip && /^;;   --seed / { skip = 0; next }
    skip { next }
    /^\(define \(problem / { sub(/\)$/, "-" pkg "-" dest ")"); print; next }
    /^        \(or \(at pkg/ { print "        (at " pkg " " dest ")))"; next }
    { print }' "$1"
}

for s in "${SEEDS[@]}"; do
  p="grid${N}x${N}-$s"
  ppgen.sh --style grid --dimensions "$N" "$N" --airports 0 --trucks 1 --airplanes 0 \
           --packages 2 --destinations 2 --require some --seed "$s" --name "$p" -o "$p.pddl"
  for lit in $(sed -n '/(:goal/,$p' "$p.pddl" | grep -o '(at pkg[0-9]* [a-z0-9-]*)' \
               | sed 's/(at //; s/)//; s/ /:/'); do
    pkg="${lit%%:*}" d="${lit#*:}"
    g="$p-$pkg-$d"
    single_goal "$p.pddl" "$pkg" "$d" > "goals/$g.pddl"
    # planner.sh stops at twice its reachability bound by default, too few when
    # the truck must fetch a package first; a shortest plan has at most
    # 2(N-1) drives to the package, a load, 2(N-1) drives on and an unload,
    # i.e. 4(N-1)+2 actions, so 4N slices always suffice
    (cd goals && planner.sh "$g.pddl" --maxslices $((4 * N)) > "$g.log" 2>&1) || true
    grep -q '^SAT' "goals/$g.answer" || { echo "no plan for $g" >&2; exit 1; }
    # keep the problem and its plan; drop the planner's intermediates
    rm -f goals/"$g".{cnf,map,satout,scnf,wcnf,wff,log}
    # Loads and unloads cost nothing, so the cost minimisation leaves in any the
    # solver happened to choose -- e.g. loading the OTHER package at the last
    # slice.  The evidence comes from a cleaned copy without the other package's
    # loads and unloads: the rest is still a plan, since the other package
    # affects neither the truck nor the goal package.  (Its HOLDS lines are left
    # as planned; evgen reads only the OCCURS lines for action observations.)
    other=$([[ "$pkg" == pkg1 ]] && echo PKG2 || echo PKG1)
    grep -v -E "^\(OCCURS \((LOAD|UNLOAD) $other " "goals/$g.answer" > "goals/$g-clean.answer"
    nact=$(grep -c '^(OCCURS ' "goals/$g-clean.answer")
    kmax=$(( nact < MAXOBS ? nact : MAXOBS ))
    for k in $(seq 1 "$kmax"); do
      evgen.sh --problem "goals/$g.pddl" --solution "goals/$g-clean.answer" --slices "1-$k" \
               --observe drive,load,unload --recognition 1 \
               --evidence "evidence/$g-obs$k.txt" 2>/dev/null
      evgen.sh --problem "goals/$g.pddl" --solution "goals/$g-clean.answer" --slices "1-$k" \
               --observe drive,load,unload --ordering-evidence "evidence/$g-ord$k.txt" 2>/dev/null
    done
    echo "done $g ($nact actions, obs 1-$kmax)"
  done
done
