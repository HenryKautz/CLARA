#!/bin/bash
# make-instances.sh N GOALS MINDIST MAXOBS [SEEDS...]
#
# Generate SimpleGrid problems gridNxN-K.pddl (one truck at p1-1, no airports,
# airplanes or packages; GOALS possible destinations at least MINDIST road steps
# away), and for each problem and each possible destination:
#   goals/<problem>-<place>.pddl     the problem narrowed to that destination
#   goals/<problem>-<place>.answer   a shortest plan for it (planner.sh)
#   evidence/<problem>-<place>-obsK.txt  the plan's first K drives, pinned to steps
#   evidence/<problem>-<place>-ordK.txt  the same drives as an ordering only
# for K = 1..MAXOBS.  Seeds default to 1 2 3 4.  Run from SimpleGrid/.
set -euo pipefail
N="$1" GOALS="$2" MINDIST="$3" MAXOBS="$4"; shift 4
SEEDS=("$@"); [[ ${#SEEDS[@]} -gt 0 ]] || SEEDS=(1 2 3 4)
cd "$(dirname "$0")"
mkdir -p goals evidence

# The single-goal variant: the goal narrowed to one destination, the problem
# renamed, and the ppgen settings block dropped (it would not regenerate this
# file) in favour of a line saying where it came from.
single_goal() {   # single_goal <problem.pddl> <place>
  awk -v src="$1" -v dest="$2" '
    NR == 1 { print $0 "-" dest
              print ";; Single-goal variant of " src ": the goal is (at truck1 " dest ") only."
              next }
    /^;; Generated by ppgen.sh/ { skip = 1; next }
    skip && /^;;   --seed / { skip = 0; next }
    skip { next }
    /^;; [0-9]+ destinations per truck/ { next }
    /^\(define \(problem / { sub(/\)$/, "-" dest ")"); print; next }
    /^        \(or \(at truck1 / { print "        (at truck1 " dest ")))"; next }
    { print }' "$1"
}

for s in "${SEEDS[@]}"; do
  p="grid${N}x${N}-$s"
  ppgen.sh --style grid --dimensions "$N" "$N" --airports 0 --trucks 1 --packages 0 \
           --destinations "$GOALS" --mindist "$MINDIST" --seed "$s" --name "$p" -o "$p.pddl"
  for d in $(sed -n '/(:goal/,$p' "$p.pddl" | grep -o '(at truck1 [a-z0-9-]*)' \
             | sed 's/(at truck1 //; s/)//'); do
    g="$p-$d"
    single_goal "$p.pddl" "$d" > "goals/$g.pddl"
    (cd goals && planner.sh "$g.pddl" > "$g.log" 2>&1) || true
    grep -q '^SAT' "goals/$g.answer" || { echo "no plan for $g" >&2; exit 1; }
    # keep the problem and its plan; drop the planner's intermediates
    rm -f goals/"$g".{cnf,map,satout,scnf,wcnf,wff,log}
    for k in $(seq 1 "$MAXOBS"); do
      evgen.sh --problem "goals/$g.pddl" --solution "goals/$g.answer" --slices "1-$k" \
               --observe drive --recognition 1 --evidence "evidence/$g-obs$k.txt" 2>/dev/null
      evgen.sh --problem "goals/$g.pddl" --solution "goals/$g.answer" --slices "1-$k" \
               --observe drive --ordering-evidence "evidence/$g-ord$k.txt" 2>/dev/null
    done
    echo "done $g"
  done
done
